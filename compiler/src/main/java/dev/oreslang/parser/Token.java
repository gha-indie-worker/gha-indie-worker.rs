package dev.oreslang.parser;

public record Token(Type type, String lexeme, int line, int column) {
    public enum Type {
        IDENT,
        INT,
        FLOAT,
        IMAG,
        STRING,
        TEMPLATE_LITERAL,
        SYMBOL_LITERAL,

        DEFINE, CLASS, MODULE, CONTRACT, CONFORMS, NAMESPACE, IMPORT, FROM, AS, EXTENDS, IMPLEMENTS,
        TRY, CATCH, FINALLY, END, FI, IF, DO, ELSE, THEN,
        NEW, SPAWN, STOP, DONE, GPU, QUANTUM, AWAIT, RT, ASYNC, SUSPENDS, GENERATOR, NLEX, TRAP, NB, CB, SELECT, READCH, WRITECH, ACTOR, ISOACTOR, SHARED, DEF, FNC, ROUTINE, WHILE, FOR, OF, LOOP, BLOCK, BREAK, CONTINUE, YIELD, SUPER, ELSEIF, SWITCH, OVER, MATCH, MATCHES, EQ, NEQ, IS, WHEN, CASE, DEFAULT, FIRST, UNTRUSTED, TYPE, TYPEOF,
        INTERFACE, TRAIT, STRUCT, INFER, TYPES, IMPL, ABSTRACT, VOID, STATIC, PUB, PRIVATE, STRUCTURAL, RETURN, DEFER, THROW, RAISE, PANIC, RECOVER,
        VAL, CONST, LET, MUT, SELF, TRUE, FALSE, NULL, OBJ, ARR,
        CPU,

        LPAREN, RPAREN, LBRACE, RBRACE, LBRACKET, RBRACKET,
        COMMA, DOT, ELLIPSIS, SEMICOLON, COLON, DOUBLE_COLON, QUESTION, AT, BACKTICK,
        PLUS, MINUS, STAR, SLASH, PERCENT, PIPE, PIPE_FORWARD, AMP, CARET, TILDE, BANG,
        EQUAL, EQUAL_EQUAL, BANG_EQUAL,
        LT, LTE, GT, GTE,
        ARROW, FAT_ARROW,
        EOF
    }
}

